/**
 * Offline stand-ins for the agent's "hands", built so the REAL tool code runs on top of them:
 * a web transport for `createWebTools` (web_fetch/web_search), a browser controller for the real
 * `browser_*` tools, an execution provider, and MCP connectors made with the real
 * `createMcpToolSpec`. Irreversible effects (orders placed, emails sent…) are recorded so tests can
 * prove they only happen after approval.
 */
