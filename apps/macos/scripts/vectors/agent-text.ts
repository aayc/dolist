/** `[anchorId, text, line]`. */
type AnchorRow = [string, string, number];

function anchorCases(core: CoreModule, doc: string, seed: number) {
  const lines = core.anchorableLines(doc);
  // Anchors taken from the document itself, then the document edited around and inside them.
  const edits = [
    doc,
    `- [ ] New task on top\n${doc}`,
    doc.replace(/\n/, "\n\n"),
    doc.replace(/a/g, "A"),
    doc
      .split("\n")
      .filter((_, i) => i % 3 !== 1)
      .join("\n"),
    doc.split("\n").reverse().join("\n"),
  ];
  const anchors: AnchorRow[] = lines.map((l, i) => [
    i % 5 === 4 ? "" : `anc_${seed}_${i}`,
    l.text,
    l.line,
  ]);
  return edits.map((edited) => ({
    doc: edited,
    anchors,
    resolved: Object.fromEntries(
      [
        ...core.resolveLineAnchors(
          edited,
          anchors.map(([anchorId, text, line]) => ({ anchorId, text, line })),
        ),
      ].map(([id, where]) => [id, [where.line, where.text]]),
    ),
  }));
}

export function buildAgentTextVectors(core: CoreModule) {
  const lines = [...CURATED_LINES, ...sample(lineArb, 10_001, 200)]
    .filter(isWellFormed)
    .map((line) => {
      const parsed = core.parseAgentLine(line);
      return {
        line,
        parsed: parsed && [parsed.text, parsed.threadId, parsed.markerFrom],
        stripped: core.stripAgentMarker(line),
        marked: MARK_IDS.map((id) => [id, core.markAgentLine(line, id)]),
      };
    });
  const markers = MARK_IDS.map((id) => [id, core.agentMarker(id)]);
  const documents = [...CURATED_DOCS, ...sample(docArb, 10_002, 80)]
    .filter(isWellFormed)
    .map((doc) => ({
      doc,
      tasks: core.parseTasks(doc).map((t: ParsedTask) => ({
        line: t.line,
        text: t.text,
        raw: t.raw,
        textFrom: t.textFrom,
        notes: t.notes,
        links: t.links,
        agent: t.agent ?? false,
      })),
      anchorable: core.anchorableLines(doc).map((l) => [l.line, l.text]),
    }));
  const anchors = [...CURATED_DOCS, ...sample(docArb, 10_003, 40)]
    .filter(isWellFormed)
    .flatMap((doc, i) => anchorCases(core, doc, i));
  return { about: ABOUT, lines, markers, documents, anchors };
}

