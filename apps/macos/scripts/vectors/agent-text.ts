type LineEdit = { kind: string; at: number; lines: string[] };

function applyEdits(base: readonly string[], edits: readonly LineEdit[]): string[] {
  let lines = [...base];
  for (const edit of edits) {
    const at = lines.length === 0 ? 0 : edit.at % (lines.length + (edit.kind === "insert" ? 1 : 0));
    if (edit.kind === "insert") lines = [...lines.slice(0, at), ...edit.lines, ...lines.slice(at)];
    else if (edit.kind === "delete") lines = [...lines.slice(0, at), ...lines.slice(at + 1)];
    else lines = [...lines.slice(0, at), ...edit.lines, ...lines.slice(at + 1)];
  }
  return lines;
}

