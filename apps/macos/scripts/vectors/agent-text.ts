export function buildMergeVectors(core: CoreModule) {
  const diffs = sample(
    fc.tuple(
      fc.array(fc.constantFrom("a", "b", "c", "d"), { maxLength: 30 }),
      fc.array(fc.constantFrom("a", "b", "c", "d"), { maxLength: 30 }),
    ),
    10_004,
    200,
  ).map(([a, b]) => ({
    a,
    b,
    hunks: core.diffLines(a, b).map((h) => [h.start, h.end, h.lines]),
  }));
  const triples: Array<[string, string, string]> = [
    ...CURATED_MERGES,
    ...sample(tripleArb, 10_005, 400).map(([base, mine, theirs]): [string, string, string] => [
      base.join("\n"),
      applyEdits(base, mine).join("\n"),
      applyEdits(base, theirs).join("\n"),
    ]),
  ];
  const merges = triples.map(([base, local, remote]) => {
    const { text, conflict } = core.mergeText(base, local, remote);
    return { base, local, remote, text, conflict };
  });
  return { about: ABOUT, diffs, merges };
}
