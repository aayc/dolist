// ── Random edit sequences (adapted from the core's task-tracker.property.test.ts) ─────────────

interface Item {
  text: string;
  status: " " | "x" | "/";
  nested: boolean;
  notes: string[];
}

function render(items: readonly Item[]): string {
  const out: string[] = [];
  items.forEach((item, i) => {
    const indent = item.nested && i > 0 ? "  " : "";
    out.push(`${indent}- [${item.status}] ${item.text}`);
    for (const n of item.notes) out.push(`${indent}  - ${n}`);
  });
  return out.join("\n");
}

const WORDS =
  "call mom buy milk book dentist email sarah plan trip renew passport pay rent water plants fix bike review pr".split(
    " ",
  );
const wordsArb = fc
  .array(fc.constantFrom(...WORDS), { minLength: 1, maxLength: 4 })
  .map((w) => w.join(" "));
const itemArb: fc.Arbitrary<Item> = fc.record({
  text: wordsArb,
  status: fc.constantFrom<Item["status"]>(" ", "x", "/"),
  nested: fc.boolean(),
  notes: fc.array(fc.constantFrom("budget $2k", "ask Sam", "before Friday"), { maxLength: 1 }),
});

type Edit =
  | { kind: "insert"; at: number; item: Item }
  | { kind: "delete" | "backspace" | "toggle" | "note" | "nest"; at: number }
  | { kind: "retext"; at: number; text: string }
  | { kind: "type"; at: number; suffix: string }
  | { kind: "move"; from: number; to: number };

const editArb: fc.Arbitrary<Edit> = fc.oneof(
  fc.record({ kind: fc.constant("insert" as const), at: fc.nat(), item: itemArb }),
  fc.record({
    kind: fc.constantFrom("delete", "backspace", "toggle", "note", "nest"),
    at: fc.nat(),
  }),
  fc.record({ kind: fc.constant("retext" as const), at: fc.nat(), text: wordsArb }),
  fc.record({
    kind: fc.constant("type" as const),
    at: fc.nat(),
    suffix: fc.constantFrom(" ", "s", " today", "!", " [[Daily/2026-09-24]]"),
  }),
  fc.record({ kind: fc.constant("move" as const), from: fc.nat(), to: fc.nat() }),
);

function applyEdit(items: readonly Item[], edit: Edit): Item[] {
  const next = items.map((item) => ({ ...item, notes: [...item.notes] }));
  if (edit.kind === "insert") {
    next.splice(edit.at % (next.length + 1), 0, edit.item);
    return next;
  }
  if (next.length === 0) return next;
  if (edit.kind === "move") {
    const [moved] = next.splice(edit.from % next.length, 1);
    next.splice(edit.to % (next.length + 1), 0, moved!);
    return next;
  }
  const item = next[edit.at % next.length]!;
  switch (edit.kind) {
    case "delete":
      next.splice(edit.at % next.length, 1);
      break;
    case "retext":
      item.text = edit.text;
      break;
    case "type":
      item.text += edit.suffix;
      break;
    case "backspace":
      item.text = item.text.slice(0, -1);
      break;
    case "toggle":
      item.status = item.status === "x" ? " " : "x";
      break;
    case "note":
      item.notes.push("follow-up");
      break;
    case "nest":
      item.nested = !item.nested;
      break;
  }
  return next;
}

const scenarioArb = fc.tuple(
  fc.array(itemArb, { minLength: 1, maxLength: 8 }),
  fc.array(fc.array(editArb, { minLength: 1, maxLength: 3 }), { minLength: 1, maxLength: 6 }),
);

export function buildTrackerVectors(core: CoreModule): TrackerVectors {
  const sequences = [...curatedSequences(), ...targetedSequences(core)].map(
    ([name, docs, threshold]) => runSequence(core, name, docs, threshold),
  );
  sample(scenarioArb, 8001, 45).forEach(([initial, batches], i) => {
    let items = initial;
    const docs = [render(items)];
    for (const batch of batches) {
      for (const edit of batch) items = applyEdit(items, edit);
      docs.push(render(items));
    }
    sequences.push(runSequence(core, `random edits #${i + 1}`, docs));
  });
  return { about: ABOUT, sequences };
}

interface AnchorVectors {
  about: string;
  cases: Array<{
    name: string;
    doc: string;
    /** `[taskId, text, line]`. */
    anchors: Array<[string, string, number]>;
    /** `resolveTaskAnchors(doc, anchors)` as an object. */
    resolved: Record<string, number>;
  }>;
}

export function buildAnchorVectors(core: CoreModule): AnchorVectors {
  const cases: AnchorVectors["cases"] = [];
  const add = (name: string, doc: string, anchors: Array<[string, string, number]>) => {
    const map = core.resolveTaskAnchors(
      doc,
      anchors.map(([taskId, text, line]) => ({ taskId, text, line })),
    );
    cases.push({ name, doc, anchors, resolved: Object.fromEntries(map) });
  };
  add(
    "anchors follow local edits",
    "- [ ] New task on top\n- [ ] Book dentist for Tuesday\n\n- [ ] Renew passport",
    [
      ["a", "Book dentist", 0],
      ["b", "Renew passport", 1],
    ],
  );
  add("deleted task drops its anchor", "- [ ] something else entirely", [["a", "Book dentist", 0]]);
  add("empty task id is never reported", "- [ ] one\n- [ ] two", [
    ["", "one", 0],
    ["b", "two", 1],
  ]);
  add("duplicate anchor ids", "- [ ] one\n- [ ] two", [
    ["a", "one", 0],
    ["a", "two", 1],
  ]);
  add("anchors sharing a line", "- [ ] alpha\n- [ ] beta", [
    ["a", "alpha", 0],
    ["b", "alpha beta", 0],
    ["c", "gamma", 1],
  ]);
  add("duplicate texts", "- [ ] call\n- [ ] new\n- [ ] call\n- [ ] call", [
    ["a", "call", 0],
    ["b", "call", 1],
  ]);
  add("no tasks", "just prose", [["a", "anything", 0]]);
  add("no anchors", "- [ ] one", []);
  const big = Array.from(
    { length: 400 },
    (_, i) => `- [ ] Task number ${i}: follow up with vendor ${i % 17}`,
  );
  add(
    "fifty anchors in a long note",
    big.join("\n").replace("Task number 5:", "Task number 5 (edited):"),
    Array.from({ length: 50 }, (_, i): [string, string, number] => [`a${i}`, big[i]!.slice(6), i]),
  );

  const randomArb = fc.tuple(
    fc.array(itemArb, { minLength: 1, maxLength: 10 }),
    fc.array(editArb, { maxLength: 6 }),
    fc.array(fc.boolean(), { minLength: 12, maxLength: 12 }),
  );
  sample(randomArb, 9001, 80).forEach(([initial, edits, keep], i) => {
    let n = 0;
    const state = core.trackTasks([], core.parseTasks(render(initial)), {
      idFactory: () => `t${++n}`,
      now: 1,
    }).tasks;
    const doc = render(edits.reduce(applyEdit, initial));
    const anchors = state
      .filter((_, j) => keep[j % keep.length])
      .map((t): [string, string, number] => [t.id, t.text, t.line]);
    add(`random #${i + 1}`, doc, anchors);
  });
  return { about: ABOUT, cases };
}
