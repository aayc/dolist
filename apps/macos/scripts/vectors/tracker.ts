const ABOUT = "Generated by apps/macos/scripts/generate-vectors.ts from @ddl/core. Do not edit.";

/** `[id, text, status, line, depth, parentId, notes, firstSeenAt, updatedAt]`. */
type TaskRow = [string, string, string, number, number, string | null, string[], number, number];

interface Step {
  doc: string;
  now: number;
  /** Full rows; large sequences only record `ids` (the other fields come from the parser). */
  tasks?: TaskRow[];
  ids?: string[];
  diff: {
    added: string[];
    /** `[id, changes]`. */
    updated: Array<[string, string[]]>;
    statusChanged: string[];
    removed: string[];
  };
}

interface TrackerVectors {
  about: string;
  /** Each sequence starts from no tasks; ids come from a counter `t1, t2, …` shared by its steps. */
  sequences: Array<{ name: string; similarityThreshold: number | null; steps: Step[] }>;
}

const row = (t: TrackedTask): TaskRow => [
  t.id,
  t.text,
  t.status,
  t.line,
  t.depth,
  t.parentId,
  t.notes,
  t.firstSeenAt,
  t.updatedAt,
];

const diffRow = (diff: TaskDiff): Step["diff"] => ({
  added: diff.added.map((t) => t.id),
  updated: diff.updated.map((u) => [u.task.id, u.changes]),
  statusChanged: diff.statusChanged.map((s) => s.task.id),
  removed: diff.removed.map((t) => t.id),
});

function runSequence(
  core: CoreModule,
  name: string,
  docs: readonly string[],
  similarityThreshold?: number,
): TrackerVectors["sequences"][number] {
  let n = 0;
  const idFactory = () => `t${++n}`;
  let state: TrackedTask[] = [];
  const steps = docs.map((doc, i): Step => {
    const now = 1_000 * (i + 1);
    const { tasks, diff } = core.trackTasks(state, core.parseTasks(doc), {
      idFactory,
      now,
      ...(similarityThreshold === undefined ? {} : { similarityThreshold }),
    });
    state = tasks;
    const large = tasks.length > 120;
    return large
      ? { doc, now, ids: tasks.map((t) => t.id), diff: diffRow(diff) }
      : { doc, now, tasks: tasks.map(row), diff: diffRow(diff) };
  });
  return { name, similarityThreshold: similarityThreshold ?? null, steps };
}

