/** Deterministic letter salad: texts that share (almost) no bigrams with each other. */
function salad(seed: number, words = 3): string {
  let s = (seed * 2_654_435_761 + 12_345) >>> 0;
  const out: string[] = [];
  for (let w = 0; w < words; w++) {
    let word = "";
    for (let i = 0; i < 6; i++) {
      s = (Math.imul(s, 1_103_515_245) + 12_345) >>> 0;
      word += String.fromCharCode(97 + ((s >>> 16) % 26));
    }
    out.push(word);
  }
  return out.join(" ");
}

const doc = (texts: readonly string[]) =>
  texts.map((t) => (t === "" ? "" : `- [ ] ${t}`)).join("\n");

/**
 * One new task `target` (at `line`) competing for two removed tasks: `a` at `line - da` and `b` at
 * `line - db`. Every other line is an unchanged filler, so no anchor shifts anything.
 */
function competition(target: string, a: string, da: number, b: string, db: number): string[] {
  const size = Math.max(da, db) + 4;
  const line = size - 2;
  const previous = Array.from({ length: size }, (_, i) => salad(9_000 + i));
  const next = [...previous];
  previous[line - da] = a;
  previous[line - db] = b;
  next[line - da] = salad(9_500 + da);
  next[line - db] = salad(9_600 + db);
  next[line] = target;
  return [doc(previous), doc(next)];
}

function targetedSequences(core: CoreModule): Array<[string, string[], number?]> {
  const out: Array<[string, string[], number?]> = [];
  const target = "buy milk and eggs today";
  const typedFrom = "buy milk and eggs";
  const rivals = [
    "buy milk and bread today",
    "buy oat milk and eggs",
    "buy milk and eggs tomorrow",
    "buy almond milk today",
    "milk and eggs today",
  ];
  const words = target.split(" ");
  const swaps = ["oat", "bread", "tea", "soon", "now", "cheese", "fresh", "some"];
  const swapped = words.flatMap((_, i) => swaps.map((s) => words.map((w, j) => (j === i ? s : w))));
  const variants = [
    ...rivals,
    ...words.map((_, i) => words.filter((__, j) => j !== i).join(" ")),
    ...swapped.map((w) => w.join(" ")),
    ...words.flatMap((_, i) =>
      swaps.map((s) => [...words.slice(0, i), s, ...words.slice(i)].join(" ")),
    ),
    ...swapped.flatMap((w) => w.map((_, i) => w.filter((__, j) => j !== i).join(" "))),
  ].filter((v) => !core.isPrefixExtension(target, v));
  const typed = Math.max(0.9, core.diceSimilarity(target, typedFrom));
  const gap = (rival: string) => typed - core.diceSimilarity(target, rival);
  // Near ties decided by the line-distance weight (0.01 per line) …
  for (const rival of rivals) {
    const lines = Math.round(gap(rival) / 0.015);
    if (lines >= 1 && lines <= 19) {
      out.push([
        `distance weight decides: ${rival}`,
        competition(target, typedFrom, lines + 1, rival, 1),
      ]);
    }
  }
  // … and by its cap (20 lines): 30 lines away costs 0.2, neither 0.3 nor 0.15.
  const capped = variants.find((v) => gap(v) > 0.155 && gap(v) < 0.195);
  if (capped)
    out.push([`distance cap decides: ${capped}`, competition(target, typedFrom, 30, capped, 0)]);
  const beyond = variants.find((v) => gap(v) > 0.205 && gap(v) < 0.29);
  if (beyond)
    out.push([
      `distance cap still counts: ${beyond}`,
      competition(target, typedFrom, 30, beyond, 0),
    ]);
  // Still typing counts as 0.9, whatever Dice says.
  out.push([
    "prefix extension scores 0.9",
    ["- [ ] Book den", "- [ ] Book dentist appointment for Tuesday"],
    0.88,
  ]);
  // Equal scores: the first pair considered (earlier parsed task) wins.
  out.push([
    "equal scores keep document order",
    [
      doc([salad(1), salad(2), salad(3), salad(4), salad(5), "fix bike", salad(6), salad(7)]),
      doc([salad(1), salad(2), salad(3), salad(4), "fix bikes", salad(8), "fix biker", salad(7)]),
    ],
  ]);
  // Duplicate alignment ties keep the earlier task (both copies are one line from the original).
  out.push([
    "duplicate alignment ties keep the earlier task",
    [
      doc([salad(11), salad(12), salad(13), salad(14), salad(15), "call", salad(16)]),
      doc([salad(11), salad(12), salad(13), salad(14), "call", salad(17), "call", salad(16)]),
    ],
  ]);
  // Expected lines come from the nearest anchor above (shifted by 5 inserted lines here).
  const above = Array.from({ length: 30 }, (_, i) => salad(200 + i));
  const beforeShift = [...above];
  beforeShift[20] = "same";
  beforeShift[25] = "same";
  const afterShift = [
    ...above.slice(0, 15),
    ...[1, 2, 3, 4, 5].map((i) => salad(300 + i)),
    ...above.slice(15, 20),
    "same",
    ...above.slice(21, 25),
    ...above.slice(26),
  ];
  out.push(["expected lines use the anchor above", [doc(beforeShift), doc(afterShift)]]);
  // 190 × 190 open pairs fit the fuzzy budget (40k): a task moved far away is still found.
  const moved = Array.from({ length: 190 }, (_, i) => salad(1_000 + i));
  const rewritten = moved.map((t) => `${t} ok`);
  out.push([
    "fuzzy pass compares everything within its budget",
    [doc(moved), doc([rewritten.at(-1)!, ...rewritten.slice(0, -1)])],
  ]);
  // 1010 open tasks: the window shrinks to its minimum, 20 lines; a task moved 20 lines is found.
  const many = Array.from({ length: 1010 }, (_, i) => salad(5_000 + i));
  const manyRewritten = many.map((t) => `${t} ok`);
  const shuffled = [...manyRewritten];
  const [picked] = shuffled.splice(500, 1);
  shuffled.splice(520, 0, picked!);
  const [raised] = shuffled.splice(700, 1);
  shuffled.splice(680, 0, raised!);
  out.push(["windowed fuzzy pass keeps its minimum window", [doc(many), doc(shuffled)]]);
  // 500 × 450 duplicates fit the alignment budget (250k): the optimal, order-preserving alignment
  // (a greedy one would cross the pair at lines 10/11 over to lines 11/5).
  const size = 600;
  const fillers = Array.from({ length: size }, (_, i) => salad(20_000 + i));
  const before = [...fillers];
  const after = [...fillers];
  for (const line of [10, 11]) before[line] = "same";
  for (const line of [5, 11, 50]) after[line] = "same";
  for (let k = 0; k < 448; k++) before[100 + k] = "same";
  for (let k = 0; k < 497; k++) after[100 + k] = "same";
  out.push(["duplicate alignment is optimal within its budget", [doc(before), doc(after)]]);
  return out;
}

const lines = (...items: string[]) => items.join("\n");

function typing(target: string, before: string[], after: string[]): string[] {
  const docs = [lines(...before, ...after)];
  for (let length = 1; length <= target.length; length++) {
    docs.push(lines(...before, `- [ ] ${target.slice(0, length)}`, ...after));
  }
  return docs;
}

