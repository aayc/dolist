export function buildTemplateVectors(core: CoreModule): TemplateVectors {
  const contexts: Array<{
    title: string;
    date: YMD;
    now: number;
    dateFormat?: string;
    timeFormat?: string;
  }> = [
    { title: "2026-09-23", date: date(2026, 9, 23), now: Date.UTC(2026, 8, 23, 14, 5) },
    {
      title: "$& {{date}} $1",
      date: date(2026, 9, 23),
      now: Date.UTC(2026, 8, 23, 14, 5),
      dateFormat: "DD/MM",
      timeFormat: "h A",
    },
    { title: "Café 日記 🎉", date: date(2025, 12, 28), now: Date.UTC(2026, 0, 1, 7, 59, 59) },
    {
      title: "",
      date: date(2024, 2, 29),
      now: Date.UTC(2026, 2, 8, 10),
      dateFormat: "",
      timeFormat: "",
    },
  ];
  const random = sample(
    fc.record({
      title: fc.string({ unit: "grapheme", maxLength: 20 }),
      date: dateArb(1900, 2100).map(ymd),
      now: fc.integer({ min: Date.UTC(2000, 0, 1), max: Date.UTC(2040, 0, 1) }),
    }),
    3001,
    6,
  );
  const cases: TemplateVectors["cases"] = [];
  const all: Array<(typeof contexts)[number]> = [...contexts, ...random];
  for (const ctx of all) {
    if (!isWellFormed(ctx.title)) continue;
    for (const template of TEMPLATES) {
      const full = { ...ctx, date: fromYmd(ctx.date), now: new Date(ctx.now) };
      cases.push({
        template,
        title: ctx.title,
        date: ctx.date,
        now: ctx.now,
        dateFormat: ctx.dateFormat ?? null,
        timeFormat: ctx.timeFormat ?? null,
        output: core.renderTemplate(template, full),
      });
    }
  }
  return { about: ABOUT, timeZone: VECTOR_TIME_ZONE, cases };
}
